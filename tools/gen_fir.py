"""gen_fir.py - the producer for common/fir_table.h.

THE TABLE HAD NO PRODUCER. fir_table.h says "GENERATED by
gen_fir_table.py" and no generator was in the tree, so the coefficients
could be read but not rebuilt - and the one thing that needed reasoning
about them was the cutoff.

ONE CUTOFF IS NOT ENOUGH. The prototype is an interpolation filter: it
has to hold the images back when the engine reads a sample slower than
it writes output, and those images sit at multiples of the SAMPLE's
rate. How far the sample's rate is below the output's is the step, and
a filter with a fixed cutoff lets every image below it through. A bank
built at 22050 Hz played into 44100 has a step of 0.5 and a 13 kHz
image where that filter does nothing; measured against the same bank
built at 44100 it cost 15 to 26 dB between 9 and 16 kHz - the hiss that
is not in the instrument's key. TinySoundFont and SpessaSynth, rendered
over the same source, agree with each other and not with a fixed
cutoff.

THE CUTOFF IS min(1, 1/step) OF THE SAMPLE'S OWN NYQUIST, AND THE
LENGTH GOES THE OTHER WAY. Interpolating up (step under one) the
reconstruction has to stop at the SAMPLE's Nyquist - a cutoff of 1 -
and what fails is the LENGTH: eight taps hold the images back by about
twenty decibels, and a 22050 Hz sample played into 44100 puts an image
at 15261 +- f exactly where twenty decibels is audible. Reading faster
than one (step over one) the cutoff has to fall to 1/step, which is the
output's Nyquist in the sample's units, and then a wide kernel is cheap
because it is smooth. So the widest filter belongs to the FULL cutoff
and the narrowest to the smallest - the opposite of what a naive
scaling suggests, and the reason `--rate keep` was always clean: a step
of one does no interpolation at all and the kernel is a delta.

PHASES COST LESS THE LOWER THE CUTOFF. A low cutoff is a smooth
kernel, so a coarse phase grid describes it; the full cutoff is where
the sub-sample position changes the answer, so it keeps the fine grid.
That is what keeps the whole family near sixty kilobytes rather than
the two hundred a uniform [1024][32] would take.

    python tools/gen_fir.py > common/fir_table.h
"""
import math
import sys

# (cutoff as a fraction of the sample's own Nyquist, taps, phases)
FAMILY = [
    # The top row stops at 0.70 of the sample's Nyquist, not at it.
    # An image of content near the sample's Nyquist lands just ABOVE
    # it - a 22050 Hz sample played into 44100 puts one at 11.05 kHz
    # against an 11.025 kHz Nyquist - and no filter can reject
    # twenty-five hertz above its own cutoff. Moving the cutoff down
    # puts the transition band where the images are. Measured on the
    # piano at key 60, the top two octaves came back 18 dB of the
    # 25 dB of image the eight tap filter let through.
    (0.70, 25, 768),
    (0.55, 17, 512),
    (0.42, 13, 256),
    (0.32, 11, 128),
    (0.24, 9, 64),
]

# THE WIDEST ROW'S CUTOFF, as a fraction of the sample's own Nyquist.
# It is a property of the table this script writes: row 0 is what the
# player uses whenever it reads a sample no faster than it writes
# output, so a bank stored at `fs` keeps nothing above WIDEST_CUT*fs/2.
# The storage-rate rule in dls_resample.py divides by this number; a
# second literal 0.70 in that rule would be a second copy of the truth.
WIDEST_CUT = FAMILY[0][0]

# 14 bits of coefficient. Fifteen did not fit: the twenty-four tap
# filter's widest sum of absolute coefficients is 71924, and a full
# scale input then needs 2.36e9 of the 2.15e9 a 32-bit accumulator has
# - the mixer accumulates in `long` and the table's own comment counts
# on that. Fourteen halves the coefficients and leaves 1.18e9, and the
# quantisation it costs is -84 dB below the signal.
SHIFT = 14

BETA = 9.0


def i0(x):
    """Bessel I0 by series; only called with x <= BETA."""
    s, t = 1.0, 1.0
    for k in range(1, 40):
        t *= (x / 2.0) ** 2 / (k * k)
        s += t
        if t < 1e-18 * s:
            break
    return s


def kernel(cut, taps, phases):
    """Every phase's taps: windowed sinc at `cut`, scaled to sum 2**SHIFT.

    The window is the same Kaiser shape the project's own resampler
    uses (ksb_build.resample), beta 9. The sum is forced to exactly
    2**SHIFT on the last tap so a constant input comes out unchanged -
    a fraction of a step of drift per frame is a DC offset, and the mix
    already has one source of those.
    """
    # The centre tap is taps/2 - 1, the same index the mixer walks
    # from - it reads `pos - half + k`, and the shipped eight tap
    # table peaks at index 3 of 8. An even length sinc is symmetric
    # about a point between two taps, and putting that point at the
    # sample keeps integer positions an identity: a phase of zero
    # then reads 0,0,...,gain,...,0 and the engine passes a sample
    # through untouched, which is what a step of one has to do.
    # ODD LENGTH, CENTRE AT AN INTEGER INDEX. An even length
    # windowed sinc is symmetric about a point BETWEEN two taps,
    # and forcing symmetry there moves the kernel's own centre -
    # which is exactly what an earlier attempt here did, and the
    # top octave came back five decibels hot. The shipped eight
    # tap table was the same thing done right: a seven tap
    # symmetric kernel with the peak at index 3.
    half = (taps - 1) // 2
    i0b = i0(BETA)
    out = []
    for p in range(phases):
        frac = p / float(phases)
        row = []
        for k in range(taps):
            t = (k - half) - frac
            if t == 0.0:
                v = cut
            else:
                a = min(1.0, abs(t) / (half + 1.0))
                w = i0(BETA * math.sqrt(max(0.0, 1.0 - a * a))) / i0b
                v = math.sin(math.pi * t * cut) / (math.pi * t) * w
            row.append(v)
        s = sum(row)
        if s != 0.0:
            row = [v * (1 << SHIFT) / s for v in row]
        q = [int(round(v)) for v in row]
        # EXACT SYMMETRY, so the mixer can halve its multiplies. The
        # windowed sinc is symmetric to within a rounding step, and a
        # pair that differs by one is not worth a second multiply: the
        # two are averaged here and convolved once as their sum. The
        # sum is then forced to 2^SHIFT on the last tap.
        # NO SYMMETRY IS FORCED. A windowed sinc is symmetric about
        # where its argument is zero, and at every phase but two that
        # point falls BETWEEN two taps - so the slice is not symmetric
        # about the array's middle and averaging mirror pairs moves the
        # kernel's own centre. That turned a low pass into a double
        # peaked filter that amplified near its cutoff, which is how a
        # 0.70 cutoff came out 27 dB BRIGHTER than a 1.00 one.
        q[half] += (1 << SHIFT) - sum(q)
        out.append(q)
    return out


def main():
    w = sys.stdout.write
    nl = "\n"
    maxabs = 0
    total = 0

    w('/* fir_table.h - GENERATED by tools/gen_fir.py. Do not edit.' + nl)
    w(' *' + nl)
    w(' * A family of windowed sincs, one per cutoff, for the player\'s' + nl)
    w(' * interpolator. The cutoff a note needs is min(step, 1/step) of' + nl)
    w(' * the sample\'s own Nyquist: interpolating up, the reconstruction' + nl)
    w(' * has to stop at the sample\'s rate; reading faster than one, it' + nl)
    w(' * has to stop at the output\'s. One cutoff let every image below' + nl)
    w(' * it through, which is the hiss that is not in the instrument\'s' + nl)
    w(' * key - see tools/gen_fir.py for the measurement.' + nl)
    w(' *' + nl)
    w(' * OVERFLOW BOUND: the largest sum of absolute coefficients over' + nl)
    w(' * every phase and every cutoff is printed by the generator, so a' + nl)
    w(' * full scale input stays inside a 32-bit accumulator.' + nl)
    w(' */' + nl)
    w('#ifndef FIR_TABLE_H' + nl)
    w('#define FIR_TABLE_H' + nl + nl)
    w('#define FIR_CUTS   %d' % len(FAMILY) + nl)
    w('#define FIR_SHIFT  %d' % SHIFT + nl + nl)
    w('static const short   fir_wid[FIR_CUTS] = {%s};'
      % ', '.join(str(t) for _, t, _ in FAMILY) + nl)
    w('static const short   fir_phase[FIR_CUTS] = {%s};'
      % ', '.join(str(p) for _, _, p in FAMILY) + nl)
    w('static const short   fir_cut[FIR_CUTS] = {%s};'
      % ', '.join(str(int(round(c * 32768))) for c, _, _ in FAMILY) + nl + nl)

    for ci, (cut, taps, phases) in enumerate(FAMILY):
        rows = kernel(cut, taps, phases)
        w('/* cutoff %.2f of the sample\'s Nyquist, %d taps, %d phases */'
          % (cut, taps, phases) + nl)
        w('static const short fir_lut%d[%d][%d] = {' % (ci, phases, taps) + nl)
        for row in rows:
            w('  {%s},' % ', '.join('%6d' % v for v in row) + nl)
            total += taps
            maxabs = max(maxabs, sum(abs(v) for v in row))
        w('};' + nl + nl)

    w('static const short *const fir_at[FIR_CUTS] = {' + nl)
    for ci in range(len(FAMILY)):
        w('  &fir_lut%d[0][0],' % ci + nl)
    w('};' + nl + nl)
    w('/* The taps of one phase: cutoff c, phase p in 0..65535. Both' + nl)
    w('   macros are one line each: a macro split across lines needs a' + nl)
    w('   backslash, and a generator that forgets one writes a header' + nl)
    w('   that does not compile. */' + nl)
    w('#define FIR_TAPS(c)  (fir_wid[(c)])' + nl)
    w('#define FIR_ROW(c, p) (fir_at[(c)] + ((int)((p) * fir_phase[(c)]) >> 16) * fir_wid[(c)])' + nl + nl)
    w('#endif' + nl)

    sys.stderr.write('cutoffs %d, taps %s, phases %s' % (
        len(FAMILY), [t for _, t, _ in FAMILY], [p for _, _, p in FAMILY]) + nl)
    sys.stderr.write('coefficients %d shorts = %.1f KB' % (total, total * 2 / 1024.0) + nl)
    sys.stderr.write('worst sum |coeff| over all phases: %d' % maxabs + nl)
    sys.stderr.write('full scale accumulator bound: %d of %d'
                     % (maxabs * 32767, 2 ** 31 - 1) + nl)


if __name__ == '__main__':
    main()
