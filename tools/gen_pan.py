"""Generate common/pan_table.h: an equal-power pan, 1025 points.

The reference player pans with cos and sin over the -500..500 range, so
a centred note comes out at 0.707 of a channel on each side and the
POWER the note has is the same wherever it sits. The straight form this
used instead - keep the centre at full and ramp the far side - moves a
centred note's level by up to 6 dB depending on where a bank puts it.

1025 entries so index 0 is hard left and 1024 is hard right, both
exactly full in one channel; the two halves are cos and sin of the same
angle so their squares add to 1 within a quantisation step.

    python3 tools/gen_pan.py > common/pan_table.h
"""
import math
import sys

N = 1024
MAXV = 32767          # 8.8: 32767 is full scale, a short's own limit

out = sys.stdout
out.write(
    "/* pan_table.h - GENERATED by tools/gen_pan.py. Do not edit.\n"
    " *\n"
    " * An equal-power pan, 1025 points: 0 is hard left, 1024 hard\n"
    " * right, both 16.16. The two halves are cos and sin of the same\n"
    " * angle so the power a note carries does not move with it - see\n"
    " * the generator for why the straight form does not do that.\n"
    " */\n"
    "#ifndef KAC_PAN_TABLE_H\n"
    "#define KAC_PAN_TABLE_H\n\n")
out.write("#define PAN_POINTS %d\n\n" % (N + 1))
out.write("static const short pan_left[%d] = {\n" % (N + 1))
lv = [int(round(MAXV * math.cos(math.pi / 2.0 * i / N))) for i in range(N + 1)]
rv = [int(round(MAXV * math.sin(math.pi / 2.0 * i / N))) for i in range(N + 1)]
for i in range(0, N + 1, 8):
    out.write("    " + " ".join("%6d," % v for v in lv[i:i + 8]) + "\n")
out.write("};\n\nstatic const short pan_right[%d] = {\n" % (N + 1))
for i in range(0, N + 1, 8):
    out.write("    " + " ".join("%6d," % v for v in rv[i:i + 8]) + "\n")
out.write("};\n\n#endif /* KAC_PAN_TABLE_H */\n")

# a short table cannot hold 65536 as a short - clamp and note it
worst = max(v for v in lv + rv)
print("# entries %d, max %d" % (N + 1, worst), file=sys.stderr)
if worst > 32767:
    print("WARNING: exceeds short range, halving", file=sys.stderr)
