"""Generate common/pow2_table.h: 2^(i/256) as 16.16, one octave.

DLS states every time and every pitch offset in CENTS - time cents for a
time, cents for a pitch - with 1200 to the octave. Turning one of those
into a rate or into a pitch therefore needs 2^(v/1200), and wave.c is a
fixed point file with no floating point in it (see the note above
db_whole in common/wave.c about why).

The table covers a whole octave in 256 steps. The caller splits the
octave count out by integer division and shifts for the rest, so the
whole expression costs one division and one lookup: 1024 bytes for
every pitch and envelope modulation a bank carries.

    python3 tools/gen_pow2.py > common/pow2_table.h
"""
import sys

ENTRIES = 256
BITS = 65536


def main():
    out = sys.stdout
    out.write(
        "/* pow2_table.h - GENERATED by tools/gen_pow2.py. Do not edit.\n"
        " *\n"
        " * 2^(i/256) as 16.16 for i = 0..255: one octave, 256 steps,\n"
        " * 1024 bytes. See the generator for why this exists rather\n"
        " * than a logarithm or a pow() call.\n"
        " */\n"
        "#ifndef KAC_POW2_TABLE_H\n"
        "#define KAC_POW2_TABLE_H\n\n")
    out.write("static const long pow2_frac[%d] = {\n" % ENTRIES)
    vals = [int(round(2.0 ** (i / 256.0) * BITS)) for i in range(ENTRIES)]
    for i in range(0, ENTRIES, 8):
        out.write("    " + " ".join("%d," % v for v in vals[i:i + 8]) + "\n")
    out.write("};\n\n#endif /* KAC_POW2_TABLE_H */\n")
    if vals[0] != BITS:
        print("entry 0 is %d, expected %d" % (vals[0], BITS), file=sys.stderr)
        return 1
    return 0


sys.exit(main())
