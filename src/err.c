static int g_english = 1;   /* default English */

void lz_set_error_lang(int english) {
    g_english = english ? 1 : 0;
}

int lz_error_lang(void) {
    return g_english;
}

const char *lz_err_text(LZErr code) {
    if (code < 0 || code >= LZ_ERR_COUNT) code = LZ_ERR_COUNT - 1;
    return g_english ? LZ_ERR_EN[code] : LZ_ERR_ZH[code];
}

int lz_err_fmt(char *buf, int len, LZErr code, ...) {
    va_list ap;
    int n;
    va_start(ap, code);
    n = lz_err_fmt_v(buf, len, code, ap);
    va_end(ap);
    return n;
}

int lz_err_fmt_v(char *buf, int len, LZErr code, va_list ap) {
    const char *fmt;
    int n;

    if (!buf || len <= 0) return -1;
    if (code < 0 || code >= LZ_ERR_COUNT) code = LZ_ERR_COUNT - 1;
    fmt = g_english ? LZ_ERR_EN[code] : LZ_ERR_ZH[code];
    n = vsnprintf(buf, (size_t)len, fmt, ap);
    return n;
}
